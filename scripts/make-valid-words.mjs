// Extracts 5-letter words from an-array-of-english-words (MIT) into src/games/hunch/valid.ts.
// Run: pnpm valid-words
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const all = require("an-array-of-english-words");

const answersSrc = readFileSync("src/games/hunch/answers.ts", "utf8");
const raw = answersSrc.match(/`([\s\S]*?)`/)[1].split(/\s+/).filter(Boolean);

const words = new Set(all.filter((w) => /^[a-z]{5}$/.test(w)).map((w) => w.toUpperCase()));
for (const w of raw) words.add(w.toUpperCase());

const sorted = [...words].sort();
const body = `// Generated by scripts/make-valid-words.mjs from an-array-of-english-words (MIT). Do not edit.
const RAW = "${sorted.join(" ")}";

export const VALID: ReadonlySet<string> = new Set(RAW.split(" "));
`;
writeFileSync("src/games/hunch/valid.ts", body);
console.log(`wrote ${sorted.length} words`);
